/**
 * Generates `src/data/icons.ts` from the installed Phosphor package.
 *
 * The SVGs are inlined at build time rather than loaded through a webfont or a
 * package subpath export: this keeps the landing page free of a 144 KB icon
 * font, and avoids a bundler-specific `?raw` resolution path.
 *
 * Run after changing the icon list below: `bun run icons:generate`.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const assetDirectory = join(root, 'node_modules/@phosphor-icons/core/assets/regular');

const icons = [
	'arrow-clockwise',
	'arrow-right',
	'arrow-up-right',
	'caret-down',
	'chart-line-up',
	'check-circle',
	'clock-countdown',
	'code',
	'desktop',
	'eye',
	'gauge',
	'github-logo',
	'hard-drives',
	'info',
	'key',
	'lock-simple',
	'moon-stars',
	'plug',
	'pulse',
	'shield-check',
	'sun',
	'terminal-window',
	'users-three',
] as const;

const entries = await Promise.all(
	icons.map(async (name) => {
		const svg = await Bun.file(join(assetDirectory, `${name}.svg`)).text();
		const paths = [...svg.matchAll(/ d="([^"]+)"/g)].map((match) => match[1]);
		if (paths.length === 0) {
			throw new Error(`${name}.svg has no path data`);
		}
		return `\t'${name}': ${JSON.stringify(paths.join(' '))},`;
	}),
);

const output = `/**
 * Generated by \`bun run icons:generate\` — do not edit by hand.
 *
 * Phosphor (MIT) path data, inlined as strings so the page ships no icon webfont.
 */
export const iconPaths = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof iconPaths;
`;

await mkdir(join(root, 'src/data'), { recursive: true });
await writeFile(join(root, 'src/data/icons.ts'), output, 'utf8');
console.log(`Generated src/data/icons.ts with ${icons.length} icons`);
